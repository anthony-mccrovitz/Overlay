def nba_slate_caption(
    picks: list[dict],
    card_date: date | None = None,
    context_label: str = "NBA",
    record: str | None = None,
) -> str:
    """Caption for NBA full slate card."""
    d = card_date or date.today()
    date_str = d.strftime("%b %-d")
    lines = []
    for i, p in enumerate(picks[:5]):
        team = p.get("team", "")
        odds = int(p.get("best_odds", 0) or 0)
        edge = float(p.get("edge_pct", 0) or 0)
        book = p.get("sportsbook", "")
        market = p.get("market", "spread")
        mkt_label = "ML" if market in ("moneyline", "h2h") else ("O/U" if market == "total" else "RL")
        prefix = "🔒" if i == 0 else ("📌" if i < 3 else "•")
        lines.append(f"{prefix} {team} [{mkt_label}] {odds:+d} — +{edge:.1f}% [{book}]")
    record_line = f"\n📈 Season record: {record}" if record else ""
    tags = _nba_hashtags(d, context_label)
    return f"""Full slate. Best 5 bets across every market tonight.

{date_str} {context_label} Full Slate 🗒️
━━━━━━━━━━━━━━━
{chr(10).join(lines)}
━━━━━━━━━━━━━━━{record_line}

Model ranks every bet by edge. Spread, ML, and totals all included.

Not financial advice. Bet responsibly. 21+

{tags} #NBAslate #fullslate #NBAtonight""".strip()


def f5_caption(plays: list[dict], card_date: date | None = None) -> str:
    """Caption for F5 (First 5 Innings) totals card."""
    d = card_date or date.today()
    date_str = d.strftime("%b %-d")
    mkt_short = {"batter_hits": "Hits", "batter_home_runs": "HRs",
                 "batter_rbis": "RBIs", "batter_total_bases": "TB"}
    lines = [
        f"⚾ F5 TOTALS — {date_str}",
        "First 5 innings only. No bullpen variance. Cleaner edge.",
        "━━━━━━━━━━━━━━━",
    ]
    for p in plays[:5]:
        matchup   = p.get("matchup", "")
        direction = p.get("direction", "OVER")
        line      = p.get("line", "")
        odds      = p.get("odds", 0)
        book      = p.get("book") or p.get("sportsbook", "")
        edge      = float(p.get("edge_pct", 0) or 0)
        odds_str  = f"{int(odds):+d}" if odds else ""
        lines.append(f"• {matchup} F5 {direction} {line}  {odds_str} @ {book}  |  +{edge:.1f}%")
    lines += [
        "━━━━━━━━━━━━━━━",
        "Model uses SP ERA × opponent K-rate for first 5 only — cleaner than full-game totals.",
        "Not financial advice. 21+",
        "#MLB #sportsbetting #F5 #firstfiveinnings #MLBpicks #sharpbetting #totals #baseballbetting",
    ]
    return "\n".join(lines)


def batter_props_caption(props: list[dict], card_date: date | None = None) -> str:
    """Caption for batter props card (hits/HRs/RBIs/TB)."""
    d = card_date or date.today()
    date_str = d.strftime("%b %-d")
    mkt_short = {"batter_hits": "Hits", "batter_home_runs": "HRs",
                 "batter_rbis": "RBIs", "batter_total_bases": "TB"}
    lines = [
        f"⚾ BATTER PROPS — {date_str}",
        "Books price batters on season BA. We adjust for pitcher matchup. Gap = edge.",
        "━━━━━━━━━━━━━━━",
    ]
    for p in props[:6]:
        player    = p.get("player", "")
        market    = p.get("market", "")
        direction = p.get("direction", "OVER")
        line      = p.get("line", "")
        odds      = p.get("odds", 0)
        book      = p.get("book") or p.get("sportsbook", "")
        edge      = float(p.get("edge_pct", 0) or 0)
        odds_str  = f"{int(odds):+d}" if odds else ""
        ms        = mkt_short.get(market, market)
        lines.append(f"• {player} {direction} {line} {ms}  {odds_str} @ {book}  |  +{edge:.1f}%")
    lines += [
        "━━━━━━━━━━━━━━━",
        "Not financial advice. 21+",
        "#MLB #sportsbetting #batterprops #hitsbet #homerunbet #MLBprops #sharpbetting #propbets",
    ]
    return "\n".join(lines)


def print_nba_captions(
    picks: list[dict],
    props: list[dict],
    card_date: date | None = None,
    record: str | None = None,
    context_label: str = "NBA",
) -> None:
    """Print NBA game picks + props captions ready to copy-paste."""
    d = card_date or date.today()
    date_str = d.strftime("%b %-d")
    W = 68

    print(f"\n{'='*W}")
    print(f"  {context_label} CAPTIONS — {d.strftime('%B %d, %Y').upper()}")
    print(f"{'='*W}")

    print(f"\n── GAME PICKS {'─'*(W-15)}")
    print()
    print(nba_picks_caption(picks, date_str=date_str, record=record, card_date=d, context_label=context_label))

    if props:
        print(f"\n── PLAYER PROPS {'─'*(W-17)}")
        print()
        print(nba_props_caption(props, date_str=date_str, card_date=d, context_label=context_label))

    print(f"\n{'='*W}\n")
