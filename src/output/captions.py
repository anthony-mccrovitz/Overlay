def nba_picks_caption(
    picks: list[dict],
    date_str: str | None = None,
    record: str | None = None,
    card_date: date | None = None,
    context_label: str = "NBA",
) -> str:
    """Generate Instagram caption for NBA game picks card."""
    d = card_date or date.today()
    date_str = date_str or d.strftime("%b %-d")

    is_playin = "PLAY-IN" in context_label.upper()
    hooks = _NBA_PLAYIN_HOOKS if is_playin else _NBA_PICKS_HOOKS
    hook = hooks[d.toordinal() % len(hooks)]

    label = context_label if context_label != "NBA" else "NBA"

    pick_lines = []
    seen_matchups: set = set()
    for i, p in enumerate(picks[:6]):
        matchup  = p.get("matchup", "")
        market   = p.get("market", "spread")
        team_str = p.get("team", "")
        odds     = int(p.get("best_odds", 0) or 0)
        edge_pct = float(p.get("edge_pct", 0) or 0)
        book     = p.get("sportsbook", "")
        key = (matchup, market, team_str)
        if key in seen_matchups:
            continue
        seen_matchups.add(key)
        odds_str = f"{odds:+d}" if odds else ""
        edge_str = f"+{edge_pct:.1f}% edge"
        book_str = f" [{book}]" if book else ""
        prefix   = "🔒" if i == 0 else ("📌" if i < 3 else "•")
        if market == "total":
            pick_lines.append(f"{prefix} {team_str} ({matchup.split(' @ ')[0][:3].upper()} vs {matchup.split(' @ ')[-1][:3].upper()}) {odds_str} — {edge_str}{book_str}")
        elif market == "spread":
            pick_lines.append(f"{prefix} {team_str} {odds_str} — {edge_str}{book_str}")
        else:
            pick_lines.append(f"{prefix} {team_str} ML {odds_str} — {edge_str}{book_str}")

    picks_block = "\n".join(pick_lines)
    record_line = f"\n📈 Model record: {record}" if record else ""
    tags = _nba_hashtags(d, context_label)

    caption = f"""{hook}

{date_str} {label} Picks 🔥
━━━━━━━━━━━━━━━
{picks_block}
━━━━━━━━━━━━━━━{record_line}

Picks generated by our efficiency-rating model (ORtg/DRtg/Pace). We track every result publicly — link in bio.

Not financial advice. Bet responsibly. 21+

{tags}"""

    return caption.strip()


