_ROTATION_C = [
    "#baseballpicks", "#mlbtoday", "#baseballfan", "#baseballlife",
    "#mlbgames", "#baseballseason", "#todaysgames", "#sportstalk",
]

_ROTATION_SETS = [_ROTATION_A, _ROTATION_B, _ROTATION_C]


def _hashtags(d: date | None = None) -> str:
    """Pick a rotation set based on day of week to avoid repetition."""
    d = d or date.today()
    rotation = _ROTATION_SETS[d.weekday() % 3]
    tags = _CORE_TAGS[:5] + rotation[:5]
    return " ".join(tags)


